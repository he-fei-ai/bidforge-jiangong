import re
import unicodedata

# 强度/等级序列（用于 XV-MAT-DESIGN 同类可比性判断与档位差计算）
_CONCRETE_GRADES = ["C15", "C20", "C25", "C30", "C35", "C40", "C45",
                    "C50", "C55", "C60", "C70", "C80", "CF40", "CF50"]
_REBAR_GRADES = ["HPB300", "HRB335", "HRB400", "HRB500"]
_MORTAR_GRADES = ["M5", "M7.5", "M10", "M15", "M20"]

_GRADE_TABLES = {
    "concrete": _CONCRETE_GRADES,
    "rebar": _REBAR_GRADES,
    "mortar": _MORTAR_GRADES,
}

# 中文数字/罗马数字 → 系列映射（查表优先，未命中照抄原文）
_REBAR_ALIAS = {
    "三级钢": "HRB400", "Ⅲ级钢": "HRB400", "III级钢": "HRB400",
    "二级钢": "HRB335", "Ⅱ级钢": "HRB335", "II级钢": "HRB335",
    "一级钢": "HPB300", "Ⅰ级钢": "HPB300", "I级钢": "HPB300",
}


def _half_width(text: str) -> str:
    """全角转半角 + 去内部空格 + 字母大写。

    ✅ 防御：非字符串（如序列类 list 值）先安全转字符串，
    避免 unicodedata.normalize 抛 TypeError 中断归一化流程。
    """
    if not isinstance(text, str):
        text = "" if text is None else str(text)
    text = unicodedata.normalize("NFKC", text)
    return re.sub(r"\s+", "", text).upper()


def normalize_material_spec(value: str) -> str:
    """材料规格等级归一：C 30→C30、Ｃ30→C30、Ⅲ级钢→HRB400。

    仅当值形似规格等级（含等级模式）时归一，其余原样返回，
    保证普通文本值不受影响。"""
    if not value:
        return value or ""
    # ✅ 防御：序列类（list）等非字符串入口先安全转型，避免 .replace 抛错
    if not isinstance(value, str):
        value = str(value)
    v = _half_width(value)
    v = _REBAR_ALIAS.get(v, v)
    if re.fullmatch(r"[CM]\d+(\.\d+)?", v):
        return v
    if re.fullmatch(r"HRB\d+", v):
        return v
    # 原文含等级子串（如"C30及以上"）→ 仅替换子串写法
    normalized = value
    for alias, std in _REBAR_ALIAS.items():
        normalized = normalized.replace(alias, std)
    half = _half_width(normalized)
    if re.search(r"(?:^|[^A-Z0-9])C\d+", half):
        return half
    if re.search(r"HRB\d+", half):
        return half
    return value


def normalize_machinery_name(name: str) -> str:
    """机械名称归一：塔式起重机→塔吊、液压挖掘机→挖掘机等。

    名称中非机械部分（如"型号/数量/进场时间"后缀）原样保留。"""
    if not name:
        return name or ""
    result = name
    for std, variants in NORM_DICT_MACHINERY.items():
        for var in variants:
            if var in result:
                result = result.replace(var, std)
                break
    return result


def normalize_process_name(name: str) -> str:
    """工序名归一：变体 → 标准名（用于序列 LCS 比对）。

    ✅ 增强：除"完全相同/命中变体列表"外，支持变体作为名称子串命中
    （如"钢筋制作与绑扎施工"含变体"钢筋制作与绑扎"），使序列比对
    不再因工序名前后缀差异而误判为不同工序。
    """
    if not name:
        return name or ""
    n = re.sub(r"\s+", "", str(name))
    for std, variants in NORM_DICT_PROCESS.items():
        if n == std or n in variants:
            return std
    for std, variants in NORM_DICT_PROCESS.items():
        for var in variants:
            if len(var) >= 2 and var in n:
                return std
    return name


def normalize_unit(unit: str) -> str:
    """计量单位归一：台套→台、米→m、日→天、％→% 等（全文口径统一）。

    未命中别名表时原样返回；空值/null/无 → 返回空字符串。
    """
    if not unit:
        return ""
    u = str(unit).strip()
    if u in ("", "null", "None", "none", "无", "-", "—"):
        return ""
    return UNIT_ALIASES.get(u, u)


def grade_rank(value: str) -> tuple[str, int] | None:
    """识别值所属等级序列与档位序号。

    返回 (序列名, 档位下标)；不属于任何序列返回 None。
    支持范围值前缀（"C30及以上"取主等级）。"""
    v = _half_width(value)
    v = _REBAR_ALIAS.get(v, v)
    m = re.match(r"^(CF)?([C]\d{2,3})", v)
    if m:
        key = "CF" if m.group(1) else "concrete"
        table = [g for g in _CONCRETE_GRADES
                 if (g.startswith("CF") == (key == "CF"))]
        g = m.group(0)
        if g in table:
            return ("concrete", table.index(g))
        return None
    if re.match(r"^HRB\d+", v):
        v2 = re.match(r"^(HRB\d+)", v).group(1)
        if v2 in _REBAR_GRADES:
            return ("rebar", _REBAR_GRADES.index(v2))
        return None
    m = re.match(r"^M(\d+(?:\.\d+)?)", v)
    if m:
        for i, g in enumerate(_MORTAR_GRADES):
            if g == f"M{m.group(1)}":
                return ("mortar", i)
    return None


def is_range_value(value: str) -> str | None:
    """识别范围值（"C30及以上"/"不低于C30"/"≥C30"），返回主等级。"""
    v = _half_width(value)
    m = re.match(r"^(?:不低于|大于等于|≥)?((?:CF)?C\d{2,3}|HRB\d+|M\d+)(?:及以上|以上|或以上)?$", v)
    if m and (m.group(1) != _half_width(value) or "及以上" in _half_width(value)
              or "以上" in _half_width(value)):
        return m.group(1)
    return None

#   新增 builder 统一走 _chapter / _nine_chapter 声明式装配，既保证九章骨架
#   与既有 builder 完全同源（编号仍由 renumber_outline 统一重排），又避免每个
#   builder 重复书写九次 helper 调用脚手架而引入漏章/错序缺陷。）


def _chapter(title: str, desc: str, secs: list[tuple[str, str, list[tuple[str, str]]]]) -> dict:
    """按 [(二级标题, 二级说明, [(三级标题, 三级说明), ...]), ...] 装配一章。"""
    ch = C(title, desc)
    for sec_title, sec_desc, leaves in secs:
        S(ch, sec_title, sec_desc, leaves)
    return ch


def _nine_chapter(
    *,
    overview: list[tuple[str, str, list[tuple[str, str]]]],
    basis: list[tuple[str, str]],
    plan: tuple[str, str, str],
    technique: list[tuple[str, str, list[tuple[str, str]]]],
    safety: list[tuple[str, str, list[tuple[str, str]]]],
    personnel: str,
    acceptance: tuple[list[str], str],
    emergency: list[tuple[str, str]],
    calc: tuple[list[str], list[str]],
    overview_desc: str = "危大工程概况、施工条件与技术保证",
    technique_desc: str = "技术参数、工艺流程、施工方法与检查要求",
    safety_desc: str = "组织保障、技术措施、监测监控",
) -> list[dict]:
    """装配九大章节标准目录树（未编号，交由 renumber_outline 统一重排）。

    章节顺序严格对齐建办质〔2018〕31 号 / 〔2021〕48 号九大章节：
    工程概况 / 编制依据 / 施工计划 / 施工工艺技术 / 施工安全保证措施 /
    施工管理及作业人员配备和分工 / 验收要求 / 应急处置措施 / 计算书及相关图纸。
    """
    return [
        _chapter("工程概况", overview_desc, overview),
        _basis_chapter(basis),
        _plan_chapter(*plan),
        _chapter("施工工艺技术", technique_desc, technique),
        _chapter("施工安全保证措施", safety_desc, safety),
        _personnel_chapter(personnel),
        _acceptance_chapter(*acceptance),
        _emergency_chapter(emergency),
        _calc_chapter(*calc),
    ]

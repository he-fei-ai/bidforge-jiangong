"""
outline_templates 拆分 · 结构辅助与通用章装配（叶子模块，零内部依赖）。
包含 _n / C / S、六个通用章装配函数、_chapter / _nine_chapter。
"""

from __future__ import annotations

# ------------------------------------------------------------------ 结构辅助


def _n(title: str, desc: str = "") -> dict:
    """三级节点（条）"""
    return {"title": title, "description": desc, "children": []}


def C(title: str, desc: str = "") -> dict:
    """一级节点（章）"""
    return {"title": title, "description": desc, "children": []}


def S(ch: dict, title: str, desc: str = "", subs: list[tuple[str, str]] | None = None) -> dict:
    """向章 ch 追加二级节点（节）；subs 为 [(条标题, 条说明)]"""
    node = {
        "title": title,
        "description": desc,
        "children": [_n(t, d) for t, d in (subs or [])],
    }
    ch["children"].append(node)
    return node


